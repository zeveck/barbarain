// Sell price (DATA_SPEC §14): treasures `value`, found gear `sell`, else half `price`; key items never.
export function sellPrice(id) {
  const it = ITEMS[id];
  if (!it || it.kind === 'key' || it.kind === 'companion') return null;
  if (it.kind === 'treasure') return it.value;
  if (it.sell != null) return it.sell;
  return it.price != null ? Math.floor(it.price / 2) : null;
}
